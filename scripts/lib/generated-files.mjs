import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync, unlinkSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';

export const GENERATED_MARKER = '# Generated by scripts/sync-docs.mjs; edit the tech_stack source.';
const START = '# BEGIN knowledge-tree generated files';
const END = '# END knowledge-tree generated files';
const LEGACY_IGNORE = '# 章节页面由 scripts/sync-docs.mjs 从 tech_stack/ 原件生成，属构建产物不入库。\n# 手写的 index.md 通过 !index.md 保留入库。\n*.md\n!index.md\n';

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const item of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, item.name);
    if (item.isDirectory()) walk(path, out);
    else if (item.isFile()) out.push(path);
  }
  return out;
}

function ignoreContent(previous, names) {
  let custom = previous === LEGACY_IGNORE ? '' : previous;
  const begin = custom.indexOf(START);
  if (begin >= 0) {
    const end = custom.indexOf(END, begin);
    if (end < 0) throw new Error('生成 .gitignore 管理区缺少结束标记');
    custom = custom.slice(0, begin) + custom.slice(end + END.length).replace(/^\n/, '');
  }
  custom = custom.trimEnd();
  const block = names.length ? [START, ...names.sort().map((name) => `/${name}`), END].join('\n') : '';
  return [custom, block].filter(Boolean).join('\n\n') + (custom || block ? '\n' : '');
}

/** Build a pure plan. Unknown Markdown and hand-written index pages are never deleted. */
export function planGeneratedFiles({ docs, generated, articlePaths, downloadPaths = [] }) {
  const write = [...generated];
  const remove = [];
  const expected = new Set(articlePaths);
  const dirs = new Map();
  for (const path of [...articlePaths, ...downloadPaths]) {
    const dir = dirname(path);
    if (!dirs.has(dir)) dirs.set(dir, []);
    dirs.get(dir).push(basename(path));
  }
  for (const path of walk(docs)) {
    if (basename(path) === '.gitignore') {
      const text = readFileSync(path, 'utf8');
      if ((text === LEGACY_IGNORE || text.includes(START)) && !dirs.has(dirname(path))) dirs.set(dirname(path), []);
    }
    if (/\.md$/.test(path) && !expected.has(path) && basename(path) !== 'index.md') {
      const text = readFileSync(path, 'utf8');
      // Only files carrying our exact frontmatter marker belong to the generator.
      if (text.startsWith(`---\n${GENERATED_MARKER}\n`)) remove.push(path);
    }
  }
  for (const [dir, names] of dirs) {
    const path = join(dir, '.gitignore');
    const content = ignoreContent(existsSync(path) ? readFileSync(path, 'utf8') : '', names);
    if (content) write.push({ path, content });
    else if (existsSync(path)) remove.push(path);
  }
  return { write, remove };
}

export function checkFilePlan(plan) {
  return [
    ...plan.write.flatMap(({ path, content }) => !existsSync(path) ? [`missing: ${path}`] : readFileSync(path, 'utf8') !== content ? [`stale: ${path}`] : []),
    ...plan.remove.filter(existsSync).map((path) => `extra generated file: ${path}`),
  ];
}

export function applyFilePlan(plan) {
  for (const { path, content } of plan.write) {
    mkdirSync(dirname(path), { recursive: true });
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) writeFileSync(path, content);
  }
  for (const path of plan.remove) unlinkSync(path);
}
